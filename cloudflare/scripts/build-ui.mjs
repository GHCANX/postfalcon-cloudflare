// Builds what the Worker serves for the browser UI from the Docker app's own
// views and static files, so the two stay one source of truth:
//   - src/views/generated.ts : every EJS view precompiled to a plain function
//     (EJS compiles with `new Function` at runtime, which Workers forbid).
//   - public/                : ../public (minus uploads/vendor) + FullCalendar
//     + overrides/public/*, which replace same-named files.
// Run by `npm run build:ui`; the outputs are git-ignored.
import ejs from "ejs";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(root, "..");

// ES modules are strict, so `with (locals)` is a syntax error. Compile without it
// and declare every free identifier a template reads as a local taken from `locals`.
const KEYWORDS = new Set("break case catch class const continue debugger default delete do else export extends finally for function if import in instanceof let new return super switch this throw try typeof var void while with yield await async of true false null undefined".split(" "));
function withoutWith(source) {
  const code = source.slice(source.indexOf("var __output"))
    .replace(/__append\((?:"(?:[^"\\]|\\.)*")\)/g, "")
    .replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*|"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|`(?:[^`\\]|\\.)*`/g, '""');
  const declared = new Set(["locals", "escapeFn", "include", "rethrow", "__output", "__append", "escape", "encode_char", "_ENCODE_HTML_RULES", "_MATCH_HTML", "__line", "__lines", "__filename"]);
  for (const m of code.matchAll(/\b(?:var|let|const|function)\s+([A-Za-z_$][\w$]*)/g)) declared.add(m[1]);
  for (const m of code.matchAll(/\b(?:var|let|const)\s*[\[{]([^}\]]*)[}\]]/g)) {
    for (const part of m[1].split(",")) declared.add(part.split(/[:=]/).pop().trim().split(/\s/)[0]);
  }
  // `const a = 1, b = 2` — every declarator in a list.
  for (const m of code.matchAll(/\b(?:var|let|const)\s+([^;\n]+)/g)) {
    for (const part of m[1].split(",")) {
      const d = part.match(/^\s*([A-Za-z_$][\w$]*)\s*(?:=|$)/);
      if (d) declared.add(d[1]);
    }
  }
  const free = new Set();
  for (const m of code.matchAll(/(?<![\w$.])([A-Za-z_$][\w$]*)/g)) {
    const name = m[1];
    if (!KEYWORDS.has(name) && !declared.has(name) && !(name in globalThis)) free.add(name);
  }
  const names = [...free];
  if (!names.length) return source;
  const declaration = `\n  var { ${names.join(", ")} } = locals || {};`;
  return source.replace(/(\n\s*var __output = "";)/, (match) => match + declaration);
}

// --- views -----------------------------------------------------------------
const viewsDir = join(repo, "views");
const entries = [];
for (const [dir, prefix] of [[viewsDir, ""], [join(viewsDir, "partials"), "partials/"]]) {
  for (const file of readdirSync(dir).filter((name) => name.endsWith(".ejs"))) {
    const source = readFileSync(join(dir, file), "utf8");
    const render = ejs.compile(source, { client: true, compileDebug: false, _with: false, filename: join(dir, file) });
    entries.push(`  ${JSON.stringify(prefix + file.replace(/\.ejs$/, ""))}: ${withoutWith(render.toString())},`);
  }
}
mkdirSync(join(root, "src/views"), { recursive: true });
writeFileSync(
  join(root, "src/views/generated.ts"),
  `// @ts-nocheck -- generated by scripts/build-ui.mjs from ../views; do not edit.\n` +
    `export const ASSET_VERSION = ${JSON.stringify(Date.now().toString(36))};\n` +
    `export const TEMPLATES: Record<string, (locals: object, escapeFn: (value: unknown) => string, include: (path: string, data?: object) => string, rethrow: (...args: unknown[]) => never) => string> = {\n${entries.join("\n")}\n};\n`,
);

// --- static files ----------------------------------------------------------
const out = join(root, "public");
rmSync(out, { recursive: true, force: true });
cpSync(join(repo, "public"), out, {
  recursive: true,
  filter: (path) => {
    const rel = relative(join(repo, "public"), path).split("\\").join("/");
    return rel !== "uploads" && !rel.startsWith("uploads/") && rel !== "vendor" && !rel.startsWith("vendor/");
  },
});
const calendar = join(root, "node_modules/fullcalendar/index.global.min.js");
if (existsSync(calendar)) {
  mkdirSync(join(out, "vendor/fullcalendar"), { recursive: true });
  cpSync(calendar, join(out, "vendor/fullcalendar/index.global.min.js"));
} else {
  console.warn("fullcalendar not installed; the calendar will not load");
}
const overrides = join(root, "overrides/public");
if (existsSync(overrides)) cpSync(overrides, out, { recursive: true });
console.log(`UI built: ${entries.length} templates, static files in public/`);
